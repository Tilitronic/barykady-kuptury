#!/usr/bin/env node
/**
 * T-034 — generate `robots.txt` and `sitemap.xml` into the Quasar build output.
 *
 * WHY a post-build script instead of `public/` files:
 * - The sitemap needs an absolute origin. `VITE_SITE_URL` is the single
 *   documented source for that origin (docs/environment.md); baking a domain
 *   into a committed file would invent an owner-supplied fact (AGENTS.md rule 6)
 *   and would break preview deploys.
 * - The path list comes from `src/features/seo/public-paths.json`, which a unit
 *   test keeps in sync with the real route table.
 *
 * Rendering mode (D-10): the launch build is an SPA, so content-dependent
 * detail routes (`projects/:slug`, `publications/:slug`,
 * `about/documents/:slug`) cannot be enumerated at build time. They are
 * deliberately absent here; see docs/environment.md for the documented manual /
 * future-prerender step.
 *
 * Behaviour when `VITE_SITE_URL` is unset:
 * - `robots.txt` is still written (its `Disallow` rules do not need an origin);
 *   only the `Sitemap:` line is omitted, because a wrong host is worse than no
 *   declaration;
 * - `sitemap.xml` is skipped with a loud warning. Netlify production and the
 *   Playwright build both set the variable.
 *
 * Usage: node scripts/generate-seo-files.mjs [--site-url https://example.org]
 *        [--out dist/spa]
 */

import { readFile, stat, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const APP_ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));

/** Locale order mirrors `SUPPORTED_LOCALES`; the URL contract is en|pl|uk. */
const LOCALES = ["en", "pl", "uk"];

/** `x-default` always points at the product default locale (PRD §2). */
const DEFAULT_LOCALE = "en";

function readFlag(name, fallback) {
  const inline = process.argv.find(arg => arg.startsWith(`--${name}=`));
  if (inline) {
    return inline.slice(name.length + 3);
  }

  const index = process.argv.indexOf(`--${name}`);
  if (index === -1) {
    return fallback;
  }

  return process.argv[index + 1] ?? fallback;
}

/** Minimal dotenv reader: only what a generator needs (no interpolation). */
async function readDotEnvValue(name) {
  const candidate = join(APP_ROOT, ".env.local");
  const text = await readFile(candidate, "utf8").catch(() => "");
  for (const line of text.split(/\r?\n/)) {
    const match = /^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/.exec(line);
    if (match === null || match[1] !== name) {
      continue;
    }
    return match[2].replace(/^["']|["']$/g, "").trim();
  }
  return undefined;
}

function normaliseSiteUrl(raw) {
  const trimmed = raw?.trim() ?? "";
  if (trimmed === "") {
    return null;
  }

  let parsed;
  try {
    parsed = new URL(trimmed);
  } catch {
    console.warn(`[seo] VITE_SITE_URL is not a valid URL: ${trimmed}`);
    return null;
  }

  if (parsed.protocol !== "http:" && parsed.protocol !== "https:") {
    console.warn(
      `[seo] VITE_SITE_URL must be http(s), got ${parsed.protocol} — ignoring it`
    );
    return null;
  }

  return trimmed.replace(/\/+$/, "");
}

async function resolveSiteUrl() {
  const flagged = readFlag("site-url", undefined);
  return normaliseSiteUrl(
    flagged ??
      process.env.VITE_SITE_URL ??
      process.env.SITE_URL ??
      (await readDotEnvValue("VITE_SITE_URL"))
  );
}

function buildRobots(siteUrl) {
  const lines = [
    "# T-034 — generated by scripts/generate-seo-files.mjs; do not edit dist/.",
    "User-agent: *",
    "Allow: /",
    "",
    "# Private surfaces. The locale prefix makes the wildcard form the correct",
    "# rule for /{en|pl|uk}/admin/**; /api/ is server-only infrastructure.",
    "Disallow: /*/admin",
    "Disallow: /api/",
    ""
  ];

  if (siteUrl !== null) {
    lines.push(`Sitemap: ${siteUrl}/sitemap.xml`, "");
  }

  return lines.join("\n");
}

function buildSitemap(paths, siteUrl) {
  const body = [];

  for (const path of paths) {
    for (const locale of LOCALES) {
      const loc = `${siteUrl}/${locale}${path}`;
      const alternates = [
        ...LOCALES.map(
          alternate =>
            `    <xhtml:link rel="alternate" hreflang="${alternate}" href="${siteUrl}/${alternate}${path}"/>`
        ),
        `    <xhtml:link rel="alternate" hreflang="x-default" href="${siteUrl}/${DEFAULT_LOCALE}${path}"/>`
      ];
      body.push("  <url>", `    <loc>${loc}</loc>`, ...alternates, "  </url>");
    }
  }

  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">',
    // URLs are generated from a fixed path list, so escaping is not required;
    // keep the comment here rather than adding an XML library dependency.
    ...body,
    "</urlset>",
    ""
  ].join("\n");
}

async function main() {
  const outDir = resolve(APP_ROOT, readFlag("out", "dist/spa"));
  const indexHtml = join(outDir, "index.html");

  if ((await stat(indexHtml).catch(() => null)) === null) {
    console.error(
      `[seo] ${indexHtml} not found — run the Quasar build before generating SEO files.`
    );
    process.exitCode = 1;
    return;
  }

  const paths = JSON.parse(
    await readFile(
      new URL("../src/features/seo/public-paths.json", import.meta.url),
      "utf8"
    )
  );
  if (!Array.isArray(paths) || paths.some(path => typeof path !== "string")) {
    throw new Error("public-paths.json must be an array of strings");
  }

  const siteUrl = await resolveSiteUrl();

  await writeFile(join(outDir, "robots.txt"), buildRobots(siteUrl), "utf8");

  if (siteUrl === null) {
    console.warn(
      "[seo] VITE_SITE_URL is not set — wrote robots.txt without a Sitemap line " +
        "and skipped sitemap.xml. Set it for production builds (docs/environment.md)."
    );
    return;
  }

  await writeFile(
    join(outDir, "sitemap.xml"),
    buildSitemap(paths, siteUrl),
    "utf8"
  );
  console.log(
    `[seo] wrote robots.txt + sitemap.xml (${paths.length * LOCALES.length} URLs, ${siteUrl})`
  );
}

await main();
